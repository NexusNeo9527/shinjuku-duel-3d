import assert from "node:assert/strict";
import * as THREE from "three";
import { Game3D } from "../src/Game3D.js";
import { DomainDynamics } from "../src/three/DomainDynamics.js";

const game = new Game3D(); game.start("dual");
game.timeStop = game.hitStop = 0;
const gojo = game.entities.find(e => e.charId === "gojo"), sukuna = game.entities.find(e => e.charId === "sukuna");
gojo.x = sukuna.x = gojo.z = sukuna.z = 0; sukuna.domainCharge = 100;
assert.equal(game.tryCast(sukuna,3),true);
game.timeStop = game.hitStop = 0;
const shrine = game.domains[0];
assert.equal(game.trySimpleDomain(gojo),true); game.updateDomains(.2);
assert.equal(shrine.tickSerial,1);
assert.equal(shrine.visualTargets[0].blocked,true,"visual hits reflect actual protected ticks");
const scene = new THREE.Scene(), dynamics = new DomainDynamics(scene);
dynamics.sync(game);
const entry = dynamics.entries.get(shrine), geometry = entry.geometry;
assert.ok(geometry.drawRange.count > 0,"Shrine has visible slash ribbons");
assert.ok(geometry.drawRange.count <= geometry.attributes.position.count,"fixed buffer cannot overflow");
gojo.simpleDomainTimer = 0; game.updateDomains(.4);
assert.equal(shrine.visualTargets[0].blocked,false,"visible hits resume after protection ends");
dynamics.sync(game);
assert.equal(dynamics.entries.get(shrine).geometry,geometry,"frames reuse the same GPU buffer");
assert.ok([...geometry.attributes.position.array].every(Number.isFinite));
const voidDomain = {...shrine,type:"void",radius:80,life:4,maxLife:5};
game.domains = [voidDomain]; dynamics.sync(game);
const voidEntry = dynamics.entries.get(voidDomain);
assert.ok(voidEntry.streams.visible);
const positions = voidEntry.lineGeometry.attributes.position.array.slice();
voidDomain.life -= .25; dynamics.sync(game);
assert.notDeepEqual(voidEntry.lineGeometry.attributes.position.array,positions,"Void information trails move over time");
assert.ok([...voidEntry.lineGeometry.attributes.position.array].every(Number.isFinite));
let disposed = false; voidEntry.geometry.addEventListener("dispose",()=>{disposed=true;});
game.domains = []; dynamics.sync(game);
assert.equal(dynamics.entries.size,0); assert.equal(scene.children.length,0); assert.ok(disposed);
dynamics.clear();
console.log("Domain dynamics: sure-hit snapshots, blocked hits, moving Void trails, bounded buffer reuse and cleanup verified.");
